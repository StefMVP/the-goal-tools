"""Load the data corpus from data/."""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ["chapters", "concepts", "tools", "sources", "books"]


def load():
    src = "data"
    out = {"origin": src}
    for n in NAMES:
        p = os.path.join(ROOT, src, n + ".json")
        out.update(json.load(open(p)) if os.path.exists(p) else {n: []})
    out["examples"] = {os.path.basename(p)[:-4]: open(p).read() for p in sorted(glob.glob(os.path.join(ROOT, "examples", "*.csv")))}
    out["diagrams"] = {}
    for p in sorted(glob.glob(os.path.join(ROOT, src, "diagrams", "*.json"))):
        d = json.load(open(p))
        out["diagrams"][d["id"]] = d
    return out


def bundle_js():
    return "/* Generated by scripts/build-data.py. Do not edit. */\nwindow.GOAL_DATA = " + json.dumps(load(), ensure_ascii=False, separators=(",", ":")) + ";\n"
